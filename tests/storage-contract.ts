import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { type CreatorStore } from '../lib/db';
import { profileSchema } from '../lib/model';
import { enqueue, runNext } from '../lib/jobs';
import { all, first, safeId, jsonObject } from '../lib/storage/driver';
export async function storageContract(store: CreatorStore) {
  const db = store.database;
  const source = { provider: 'test', identifier: 'synthetic-fixture', permission: 'Own synthetic test data' };
  const profile = profileSchema.parse({ username: 'synthetic_identity', instagram_user_id: 'identity-1', followers_count: 0, synthetic: true });
  assert.equal(await store.saveProfile(profile, source), 'inserted');
  assert.equal(await store.saveProfile({ ...profile, username: 'synthetic_renamed', followers_count: null }, source), 'updated');
  let state = await store.snapshot();
  assert.equal(state.creators.length, 1);
  const creator = state.creators[0];
  assert.equal(creator.username, 'synthetic_renamed');
  assert.equal(creator.followers_count, 0);
  assert.equal(creator.metrics.length, 2);
  assert.equal(creator.metrics[0].followers_count, null);
  assert.equal(typeof creator.id, 'number');
  assert.equal(typeof creator.updated_at, 'string');
  assert.equal(creator.validation_status, 'needs_review');
  assert.equal(creator.sources[0].permission_reference, source.permission);
  await assert.rejects(store.saveProfile({ ...profile, username: 'synthetic_renamed', instagram_user_id: 'conflicting-id' }, source), /Conflicting/);
  const other = profileSchema.parse({ username: 'synthetic_other', instagram_user_id: 'identity-2', synthetic: true });
  await store.saveProfile(other, source);
  await assert.rejects(store.saveProfile({ ...profile, username: 'synthetic_other' }, source), /collision/);
  const before = (await store.snapshot()).creators.length;
  await assert.rejects(store.saveProfile(profileSchema.parse({ username: 'must_rollback' }), { ...source, permission: null as unknown as string }));
  assert.equal((await store.snapshot()).creators.length, before);
  await store.review(safeId(creator.id), 'reviewed');
  assert.equal((await first(db, 'SELECT validation_status FROM creators WHERE id=$1', [safeId(creator.id)]))?.validation_status, 'reviewed');
  await store.suppress(safeId(creator.id));
  await assert.rejects(store.saveProfile({ ...profile, username: 'another_name' }, source), /suppressed/);
  assert.equal((await all(db, 'SELECT * FROM creator_metrics WHERE creator_id=$1', [safeId(creator.id)])).length, 0);
  const concurrent = profileSchema.parse({ username: 'synthetic_concurrent', synthetic: true });
  const outcomes = await Promise.all(Array.from({ length: 5 }, () => store.saveProfile(concurrent, source)));
  assert.equal(outcomes.filter(o => o === 'inserted').length, 1);
  assert.equal((await all(db, 'SELECT * FROM creators WHERE username=$1', [concurrent.username])).length, 1);
  const html = readFileSync('fixtures/creator.html', 'utf8');
  const request = { kind: 'fixture', source: 'fixtures/creator.html', permission: 'Synthetic local test fixture', content: html, limit: 10 };
  const id = await enqueue(request, store);
  await runNext(store);
  assert.equal((await first(db, 'SELECT status FROM ingestion_jobs WHERE id=$1', [id]))?.status, 'completed');
  const originalCount = (await store.snapshot()).creators.length;
  await enqueue(request, store); await runNext(store);
  assert.equal((await store.snapshot()).creators.length, originalCount);
  const cancelled = await enqueue(request, store);
  await store.cancel(cancelled);
  assert.equal((await first(db, 'SELECT status,completed_at FROM ingestion_jobs WHERE id=$1', [cancelled]))?.status, 'cancelled');
  await enqueue({ ...request, content: '<bad>' }, store); await runNext(store);
  assert.equal((await store.snapshot()).jobs[0].status, 'failed');
  const limited = await enqueue({ ...request, limit: 1 }, store); await runNext(store);
  assert.equal((await first(db, 'SELECT processed FROM ingestion_jobs WHERE id=$1', [limited]))?.processed, 1);
  await Promise.all(Array.from({ length: 5 }, () => enqueue(request, store)));
  const claimed = await Promise.all(Array.from({ length: 5 }, () => store.claimJob()));
  assert.equal(new Set(claimed.map(j => j?.id)).size, 5);
  for (const job of claimed) await store.finish(safeId(job?.id), 'cancelled');
  // A running job observes cancellation, while queued cancellation never gets claimed.
  const active = await enqueue(request, store);
  const running = await store.claimJob(); assert.equal(running?.id, active);
  await store.cancel(active); assert.equal(await store.isCancelled(active), true);
  await store.finish(active, 'cancelled');
  const release = await db.acquireWorkerLock();
  try { await assert.rejects(db.acquireWorkerLock(), /Another worker/); }
  finally { await release(); }
  const releaseAgain = await db.acquireWorkerLock(); await releaseAgain();
  state = await store.snapshot();
  assert.ok(state.logs.length > 0);
  assert.equal(jsonObject((await first(db, 'SELECT payload FROM creators WHERE username=$1', [concurrent.username]))?.payload).synthetic, true);
}
